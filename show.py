from typing import List

import matplotlib.pyplot as plt
import numpy as np


def plot_laserscan(scan: dict[str, List]) -> None:
    """
    Given a scan dictionary (representing a sensor_msgs/LaserScan message).

    this function computes the (x,y) coordinates of each range measurement and
    plots them as a scatter plot with color indicating the intensity.
    """
    # Extract scan parameters
    angle_min = scan.get("angle_min", 0.0)
    angle_increment = scan.get("angle_increment", 0.0)
    ranges = np.array(scan.get("ranges", []))
    intensities = np.array(scan.get("intensities", []))

    # Number of measurements:
    num_points = len(ranges)

    # Compute the angle for each measurement
    angles = angle_min + np.arange(num_points) * angle_increment

    # For visualization, we remove (or mask) measurements with zero or negative range
    valid = ranges > 0.0
    valid_ranges = ranges[valid]
    valid_angles = angles[valid]
    valid_intensities = (
        intensities[valid]
        if intensities.size == num_points
        else np.zeros(valid_ranges.shape)
    )

    # Convert polar to Cartesian coordinates
    x = valid_ranges * np.cos(valid_angles)
    y = valid_ranges * np.sin(valid_angles)

    # Create a scatter plot (you can also use a polar plot if preferred)
    plt.figure(figsize=(8, 8))
    sc = plt.scatter(x, y, c=valid_intensities, cmap="viridis", s=30, edgecolors="k")
    plt.xlabel("x (m)")
    plt.ylabel("y (m)")
    plt.title("LaserScan Visualization")
    plt.grid(True)
    plt.axis("equal")
    cbar = plt.colorbar(sc)
    cbar.set_label("Intensity")
    plt.show()


